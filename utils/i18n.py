def get_text(key, lang='uz', **kwargs):
    bundle = TRANSLATIONS.get(lang, TRANSLATIONS['uz'])
    text = bundle.get(key, key)
    if isinstance(text, str):
        return text.format(**kwargs)
    return text

def get_cat_text(cat_name, lang='uz'):
    """Translates category names from the database."""
    if not cat_name:
        return ""
    # Normalize name (lowercase, remove special chars if any, replace space with _)
    key = 'cat_' + cat_name.lower().replace("'", "").replace(" ", "_").replace("-", "_")
    translated = get_text(key, lang)
    
    # If get_text returns the key itself, it means translation was not found
    if translated == key:
        return cat_name
    return translated
